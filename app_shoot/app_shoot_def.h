// 拨弹控制参数（实机整定；机械参数见 robot_def.h 的 TRIGGER_STEP_RAD）
/* 拨盘驱动律（2026-10-11）：**位置闭环**，参考位置按模式两路生成（都在"一发 = TRIGGER_STEP_RAD
 * (≈13.468 rad)"这套机械量上工作）。
 *   - 单发：lib_traj_jerk 规划一条"从当前实测位置/速度走到 (当前 + 一步)、终点静止"的 jerk 受限
 *     轨迹，每拍 LibTrajStep 采样 —— 起停有包络，一步一个目标，判据是轨迹 finished。
 *   - 三发/连发：**连续转动**，不再一发一停。走的仍是同一套 lib_traj_jerk 点到点轨迹，只是
 *     行程 = 3 发 / TRIGGER_BURST_SHOTS 发（中间不停，"连续"就是这一段长轨迹本身）；
 *     连发松手后另走一条收尾轨迹停在整数发边界。判据同样是轨迹 finished。
 * 两路都把参考 position 当位置环设定值、参考 velocity 当角度环前馈（角度环输出就是速度设定值，
 * 量纲 rad/s，见 lib_traj.h 的接法表）。
 *
 * 谁决定"走不走、走几步"是 lib_fsm_table 的拨弹状态机：
 *   ch7 上升沿 → 按 ch9 模式进 单发/三发/连发；"走完一发" → step_done；
 *   单发走完回停止/关，三发/连发原地继续；ch7 下降沿按状态机规则回关。
 *
 * 2026-10-10 的开环定力矩试验（TRIGGER_TEST_TORQUE，量得无弹阈值 1.25 A / 加弹 ≈6 A）已随
 * 位置环改写移除。按计划**摩擦前馈与位置环积分留到下一轮**（本轮只上位置 P + 参考速度前馈）。 */

/*-------------------------------- 射频 → 拨盘转速 --------------------------------
 * 射频 (发/s) 是拨盘转速的唯一来源。
 *
 * 换算与参考车（half_rudder_2027 的 application/shoot/shoot.c）**完全同构**，那边写的是
 *     DJIMotorSetRef(loader, -rate * 360 * REDUCTION_RATIO_LOADER / NUM_PER_CIRCLE);  // deg/s
 * 其中 360 × 25.6 / 12 = 768 deg = 13.4045 rad。
 * ⚠ 参考车用的 25.6 是**四舍五入值**（真值 268:17 × 62:38 = 25.7214 ⇒ 13.4677 rad）。它只拿这个
 *   数算**巡航转速**（速度上 0.474% 看不出来），所以一直没暴露；我们拿它做**整数网格停位**，
 *   0.474% 就是每 211 发滑一个孔，必须用真值 —— 见 robot_def.h 的 TRIGGER_GEAR_RATIO。
 *   两车仍是同一条式子（只是各自的"每发转角"数值不同）：
 *     拨盘转速(rad/s) = 射频(发/s) × TRIGGER_STEP_RAD
 *
 * 参考车的射频档位（手柄 E 键循环，robot_cmd.c）：**6 / 8 / 10 / 12 发/s**
 * （图传 UI 那套是 8/10/12/14，referee_task.c）。它的"动态"只在**热量限幅**上 ——
 * _ShootHeatClampBurstRate() 按剩余热量与冷却速率把档位往下压，档位本身是固定四档、不查表。
 *
 * 本轮取参考车**最慢那一档 6 发/s** 用在拨盘上。改射频只改这一个数：
 * 连续转动的巡航速度与单发轨迹的速度上限都由它派生（单发一步只有 13.468 rad、够不到这个
 * 速度，实际由 TRIGGER_TRAJ_AMAX 决定，见下）。 */
#define TRIGGER_FIRE_RATE_HZ 6.0f // 射频 (发/s)：参考车最慢档
/* 拨盘转速上限 (rad/s) = 射频 × 每发转角 ≈ 6 × 13.4677 ≈ 80.81 rad/s（≈4630 deg/s）。 */
#define TRIGGER_SPEED_MAX (TRIGGER_FIRE_RATE_HZ * TRIGGER_STEP_RAD)

/* ------------------------- 轨迹上限（由参考车反推，2026-10-11） -------------------------
 * 【老代码只有一个显式速度限幅】half_rudder_2027 拨盘的 angle_PID.MaxOut = 7000（deg/s，电机轴），
 *   注释原文"此为最大9hz时的参数,如果需要更快的射速需要调整参数提高MaxOut"：
 *       7000 deg/s = 122.17 rad/s = 9.07 发/s    ← 位置环能给的最大速度指令
 *   单发/三发都跑位置环（ANGLE_LOOP），所以它们最多 122.17 rad/s。
 *   连发走速度环直驱、不受此限：手柄最高档 12 发/s ≈ 161.6 rad/s，图传最高档 14 发/s ≈ 188.5 rad/s。
 *
 * 【老代码没有任何加速度限幅】位置环饱和输出 7000 deg/s、速度环 MaxOut=50000（远超驱动层
 *   ±16384 ↔ 20 A），加速度完全由**电流限幅**决定，代码里根本没有角加速度这个量。
 *   所以 amax 只能反推 —— 用它自己的 SHOOT_SINGLE_BULLET_TIME = 150 ms（shoot.h，注释
 *   "完成1发弹丸发射的时间"）：13.404 rad 用 0.15 s，在 vmax=122.17 的梯形剖面下解出
 *       amax ≈ 2400 rad/s²（加速 0.051 s 走 3.12 rad + 巡航 0.059 s 走 7.16 rad + 减速同），
 *       总 0.161 s ≈ 150 ms ✓ 自洽。
 *   ⚠ 同一份 shoot.h 里的 SHOOT_THREE_BULLET_TIME = 300 ms 是**做不到**的：40.2 rad 即使
 *     amax→∞、全程满速也要 40.2/122.17 = 0.33 s > 0.3 s，说明它只是"不应期"不是运动时间。
 *     所以上面 150 ms 这条反推是"老代码自己认为的目标"，不是硬约束。
 *
 * 【jmax 老代码没有对应物】它靠位置环 P=14 直接饱和，等效加速度阶跃。我们走 7 段 S 曲线，
 *   jmax 太大就失去平滑意义、太小会把加/减速段拉长。取 40×amax。这是**平滑度旋钮**，
 *   不影响 vmax/amax 的物理含义。
 *
 * 【2026-10-11 第二轮：把三个上限一起调低，让收尾更温和】实测（ignore/vofa+.csv）单发收尾时
 *   机构仍有 ~30 rad/s 残余速度，冲过参考终点 0.03~0.05 发（≈0.5 rad 电机轴 ≈1.25° 拨盘轴），
 *   被空闲态"锁实测"固化成一个恒定超前偏置（不再累积，见 §发数网格）。根因是剖面太冲：
 *   实测峰值 141 rad/s **高于**参考 122 rad/s、巡航段实测一直超前参考，减速段跟不上 → 收尾
 *   时速度没降下来。故把三个上限一起调低，给位置环留跟踪余量：
 *     原 vmax 122.17 → 100、amax 2400 → 1200、jmax 120000 → 48000（保持 40×amax 的剖面形状）。
 *   代价（按 lib_traj_jerk 的 7 段剖面算）：单发 0.18 → ≈0.25 s，三发 7.5 → 5.9 发/s（仍贴着
 *   TRIGGER_FIRE_RATE_HZ 那个 6 发/s 档）；连发 5.99 发/s **不受影响**（巡航速度决定，见 §射频）。
 *   vmax 没敢再往下压：90 会让三发掉到 5.5 发/s。
 *   ✅ 2026-10-11 实机验证有效（115 次单发）：**收尾残余速度 30 → 2.2 rad/s**（根因基本消掉）、
 *     最大跟踪滞后 0.78 → 0.63 rad、|e| max 1.048 → 0.715 rad(7.8%→5.3% 步长)、
 *     |I| max 3.93 → 2.64 A（均值 0.93 → 0.61）、停机距整 1.25° → 1.13°、每发超调均值
 *     0.0345 → 0.0239 发；实测单发耗时 0.25 s（与预估吻合）。网格锚定下 115 发累计漂移
 *     +0.023 发（仍有界）。残留：实测峰速 112 仍高于参考 100（速度环跟踪超调，非轨迹问题）
 *     —— 还想压就抬 TRIGGER_ANGLE_KP 或再降 vmax，但都会牵动三发射频。 */
#define TRIGGER_TRAJ_VMAX 100.0f   // 单发/三发/收尾速度上限 (rad/s)；须 > 连发巡航 80.81 才不拖累射频
#define TRIGGER_TRAJ_AMAX 1200.0f  // 轨迹加速度上限 (rad/s²)：原 2400（老代码单发 150 ms 反推），减半
#define TRIGGER_TRAJ_JMAX 48000.0f // 轨迹 jerk 上限 (rad/s³) = 40×amax
#define TRIGGER_I_MAX 20.0f        // 速度环输出(电流)上限 (A)：M3508 硬上限，不随转速改
/* 位置环输出 = 速度设定值，限幅 (rad/s)。须 **> TRIGGER_TRAJ_VMAX**：速度前馈本身就 ≈vmax，
 * 限幅顶到 vmax 会把比例项权限整段吃掉（巡航段跟不上也没法纠）。取 ~1.25 倍留权限。 */
#define TRIGGER_ANGLE_VMAX 150.0f
/* 位置环比例系数 (1/s)：位置误差 1 rad → 速度设定值 kp rad/s。一步 13.47 rad，起步误差大、
 * 经上面限幅后近似"以最大速度追"。首轮空载**只上 P**，积分按计划留到下一轮；
 * 摩擦带来的稳态位置差由内环速度环的 PI 兜（它的积分才有意义，见 TRIGGER_VARINT_*）。
 *
 * 2026-10-11 由 10 提到 25（用户："把拨盘的位置速度环调硬"）。依据是收尾段的实测账：
 *   轨迹收尾时前馈速度已回 0，剩下的位置误差**只能靠位置环自己**挣 —— 等效电流增益
 *   = kp_angle × TRIGGER_SPEED_KP。实测每发收尾停在离目标 ~2.6 rad 处（err 2.6 rad，
 *   CH16 只有 5.8 rad/s、CH14 只有 0.78 A、CH8 只有 1.3 A），而静摩擦要 4~6 A 才破得动
 *   ⇒ 改前等效 10 × 0.08 = 0.8 A/rad，改后 25 × 0.2 = 5 A/rad。
 * ⚠ 位置环是**慢外环**，穿越频率 ≈ kp_angle rad/s = 25 rad/s（4 Hz），必须远低于速度环的
 *   穿越（≈ TRIGGER_SPEED_KP×500 ≈ 100 rad/s），两者比值 ≈1:4 才不互相打架。**别单独往
 *   上冲这一项**，要动就连速度环一起按比例动。 */
#define TRIGGER_ANGLE_KP 25.0f
/* 位置环积分上限 (rad/s)：本轮 ki=0 未启用，但**必须保持 > 0** —— 传 0 会让 lib_pid 把积分
 * 永久清零、静默退化成纯 P（本项目踩过这个坑）；下一轮打开积分时直接可用。 */
#define TRIGGER_ANGLE_I_LIMIT 5.0f
/* 速度环比例系数 (A/(rad/s))：转速误差 1 rad/s → 电流 kp A。
 * 2026-10-11 由 0.08 提到 0.2（同上：调硬）。旧值 0.08 的来历与代价见 app_shoot.c 的
 *   Config 注释（开环力矩档实测过 0.2/0.08 两点的极限环：主频 13.2/6.5 Hz **正比于 kp**，
 *   幅值却不随 kp 变 —— 幅值由摩擦非线性撑着，故当时选择保稳定、弃刚度）。
 * 现在的账不一样了：闭环变了（位置环在外、轨迹前馈在内），而收尾段的问题是**电流上不去**
 *   （见 TRIGGER_ANGLE_KP 的实测），刚度比那 6.5 Hz 的一点猎振更要紧。
 * ⚠ 稳定上限（经验）：穿越频率 ≈ kp×500 rad/s，而速度反馈低通 TRIGGER_SPEED_LPF_RC 是
 *   主滞后，穿越一旦逼近 1/(2π·rc) 就会振。0.2 对应 ~100 rad/s（16 Hz），配 3 ms
 *   （53 Hz）留 3 倍余量；再往上加必须同时减 rc 或减 LPF 阶数。 */
#define TRIGGER_SPEED_KP 0.2f
/* 速度/电流反馈一阶低通时间常数 (s)：**环路里最大的一处相位滞后**（见 app_shoot.c 的 Config
 * 注释）。2026-10-11 由 5 ms 再降到 3 ms：本次要提 TRIGGER_SPEED_KP，得先把相位还回来。
 * 拨盘编码器反馈本身很干净（静止段 meas 恒 0.000、运行纹波仅 0.16 rad/s），
 * 而任务周期本来就是 2 ms —— 再往下压（< 2 ms）就小于采样间隔、失去意义了。 */
#define TRIGGER_SPEED_LPF_RC 0.003f

/* ---------------- 单发 / 三发 / 连发：整段走**一条轨迹**，终点必落在整数发网格上 ----------------
 * 2026-10-11 第二版：上一版是"速度斜坡 × dt 积分出参考位置"，退出时要滑 v²/(2a) 才能停 ——
 * 实测 80.43 rad/s 下多滑 17.8 rad = **1.33 发**，每轮结束相位都往后漏一个多孔位。第二版
 * 后半改成和单发同一套 lib_traj_jerk 点到点（三种模式一条轨迹、终点静止）：
 *   - 单发：走到 +1×TRIGGER_STEP_RAD；三发：走到 +3× 的**一条长轨迹**、中间不停（这就是
 *     "连续转动"的本体）；连发：走到 +TRIGGER_BURST_SHOTS× 的**长轨迹**，巡航速度取射频换算值
 *     TRIGGER_SPIN_SPEED —— 射频仍由 TRIGGER_FIRE_RATE_HZ 唯一决定。
 *   - 连发松手/断开不硬停，而是**重规划**一条"到最近整数发边界、终点静止"的收尾轨迹
 *     （见 AppShootRun 的收尾段），于是停机位置永远是整数发。
 * ⚠ 2026-10-11 第三版改了**终点怎么取**：锚在**理论网格**上，不再是"实测 + N×STEP"。轨迹收尾时
 *   位置环有超调（实测冲过 ref 终点 ~0.04 发），而空闲态 ref 又锁实测把这个超调固化 —— 用实测当
 *   基准时每发的超调都被下一发继承、逐发累积，实测 35 次单发后超前 1 整格 ≈ 多送一颗弹
 *   （证据 ignore/vofa+.csv）。起点仍取实测（保轨迹连续）。
 * ⚠ 2026-10-11 第四版把网格**绝对化**（第四版之前是"相对链 + 超半格重锚"，仍在漂）：网格只在
 *   开机第一发锚一次、永不重锚。**第五版**改为"参考自持的整数链"（参考格号每发 +N，永不看实测、
 *   永不后退），整套口径集中在 §发数网格，改动都在 AppShootRun 的规划分支与结尾的 ref 生成。
 * 发数/收尾判据只有**一个**：整段轨迹 finished（三种模式同构），不再有逐发计数。
 * 中断语义（2026-10-11 用户定）：**单发/三发一旦发射就必须打完**（中途松手不打断），
 * 只有连发允许运动中停 —— 对应状态机里单发/三发没有 ch7 下降沿转移、只有连发有。 */
/* 每发规划前进量系数（对机械步距 TRIGGER_STEP_RAD 的比例）。
 * ⚠ 这是**净前进量**：网格锚定后，每发的实际净转角恒 = TRIGGER_STEP_RAD × 本系数，与收尾偏差
 *   无关（偏差只改下一发的**指令行程**，两拍相抵）。日志里 CH1 的单发指令行程因此是
 *   1 发 − 上一发**超调**（或 1 发 + 上一发**滞后**，见 §发数网格），**不是**本系数
 *   —— 别把那个数抄到这里。
 *   稳态取 1.0（一发 = 一孔）。想压收尾误差请调上面 §轨迹上限 的柔和度（vmax/amax/jmax）。
 *   机械换拨盘/孔数后要改的是 robot_def.h 的 TRIGGER_STEP_RAD，也不是这里。
 *
 * 【2026-10-12 诊断实验：暂取 0.25】单发"稳发 / 隔发 0 与 2 交替"的根因只剩两个假设：
 *   ① 机构问题（弹链/单发限位/摩擦轮）② 规划格点与机构过弹点之间有固定**相位差**。
 *   稳态一发一孔时每发都停在同一机械相位（实测 std 0.0156 孔），扫不出相位依赖 —— 所以把步距
 *   压到 **1/4 孔**：连续几发的停位相位自动遍历 0 / 0.25 / 0.5 / 0.75 孔（每 4 发一轮），
 *   **一次上电就扫完四个相位**；再用 TRIGGER_GRID_OFFSET_HOLES 旋转起点相位。
 *   判定（分析脚本 --shot-lag 会按"停位相位 mod 1 孔"分箱统计过/不过）：
 *     · 出弹率随相位**强烈起伏**（某相位几乎不出、某相位稳出）⇒ **相位差问题**，偏移就是解药；
 *     · 四个相位出弹率**一样**（都好或都差）⇒ **机构问题**，偏移扫不出东西。
 *   ⚠ 只做**单发**实验：连发巡航 TRIGGER_SPIN_SPEED 不含本系数，SCALE≠1 时连发网格的一"发"
 *     变成 1/4 孔、与真实弹数不再 1:1（物理射速不变）。实验完**务必改回 1.0**。 */
#define TRIGGER_STEP_ADVANCE_SCALE 0.25f
#define TRIGGER_STEP_ADVANCE_RAD (TRIGGER_STEP_RAD * TRIGGER_STEP_ADVANCE_SCALE)

/* 网格锚点相对**上电实测位置**的机械相位偏移（单位 = **孔**，可正可负；锚定时加到 trigger_grid_origin）。
 * 语义就是"我们以为的格点"与"机构真实过弹点"之间那个固定差 —— 用孔做单位最直观。
 * 单位换算：TRIGGER_STEP_RAD 恒 = 电机转**一孔**的角度，故本值 × TRIGGER_STEP_RAD 就是电机轴上
 * 的相位偏移，**与 TRIGGER_STEP_ADVANCE_SCALE 无关**（相位是机械量，不该随步距缩放）。
 * 单发扫描取值 0 / 0.25 / 0.5 / 0.75 孔，每档 ≥20 发，看"过/不过"是否跟着相位走。
 * ⚠ 只在**开机第一发**锚一次（trigger_grid_valid 置位后不再重锚）⇒ 每改一次本值都要重新上电。 */
#define TRIGGER_GRID_OFFSET_HOLES 0.0f

#define TRIGGER_SPIN_SPEED TRIGGER_SPEED_MAX // 连发巡航速度 (rad/s) = 射频 × 每发转角 ≈ 80.81
#define TRIGGER_BURST_SHOTS 500.0f           // 连发一次规划的发数（≈83 s @6 发/s，一场够用）
/* 连发收尾时留的减速余量 (发)：收尾目标取"当前参考位置所在格 + 本余量"向上取整的那一格
 * （**仍是整数格**，见 §发数网格），保证终点恒在前方足够远处。
 * **由物理量推导、不写死**：减速所需距离 = v²/(2·amax)（v = 连发巡航 TRIGGER_SPIN_SPEED），
 * 换算成发数再乘 1.5 余量。这样调 §轨迹上限 的 amax 时余量自动跟上 —— 写死 0.2 时若把
 * amax 减半（2400→1200），所需距离正好从 0.10 涨到 0.20 发、余量归零，就会规划出倒车轨迹。
 * ⚠ 这里留余量的理由是 **lib_traj_jerk 的可行性**（不是防退弹）：收尾时机构正以巡航速度前冲，
 *   减速距离不够 planner 就判不可行、参考冻在高速上（实测形态：ref 卡住不动、位置环猛拽）。
 *   顺带它保证这半发一定打完。 */
#define TRIGGER_BURST_STOP_MARGIN (1.5f * TRIGGER_SPIN_SPEED * TRIGGER_SPIN_SPEED / (2.0f * TRIGGER_TRAJ_AMAX * TRIGGER_STEP_ADVANCE_RAD))

